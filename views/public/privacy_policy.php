            <div class="policy-section">
                <h2 class="policy-section-title">Purpose of Data Collection</h2>
                <p>Your personal data is collected and processed solely for the following purposes:</p>
                <ul>
                    <li>Registration and identity verification of Sangguniang Kabataan members and constituents</li>
                    <li>Facilitating SK programs, events, and service requests</li>
                    <li>Generation of official records, certificates, and reports</li>
                    <li>Communication of announcements and updates relevant to your barangay</li>
                    <li>Compliance with government reporting obligations</li>
                </ul>
            </div>

            <div class="policy-section">
                <h2 class="policy-section-title">How We Store and Protect Your Data</h2>
                <p>SKonnect implements reasonable technical and organizational safeguards to protect your data, including:</p>
                <ul>
                    <li>Encrypted storage of sensitive personal information</li>
                    <li>Restricted access limited to authorized SK officials and system administrators</li>
                    <li>Regular security reviews of system access and records</li>
                    <li>Data is retained only for as long as necessary for its intended purpose or as required by law</li>
                </ul>
            </div>

            <div class="policy-section">
                <h2 class="policy-section-title">Sharing of Information</h2>
                <p>We do not sell, trade, or share your personal data with third parties, except in the following circumstances:</p>
                <ul>
                    <li>When required by law or by a competent government authority</li>
                    <li>When necessary to coordinate with the Local Government Unit (LGU) for program delivery</li>
                    <li>With your explicit consent for a specific, stated purpose</li>
                </ul>
            </div>

            <div class="policy-section">
                <h2 class="policy-section-title">Your Rights as a Data Subject</h2>
                <p>Under RA 10173, you have the right to:</p>
                <ul>
                    <li><strong>Access</strong> — request a copy of the personal data we hold about you</li>
                    <li><strong>Correction</strong> — request correction of inaccurate or outdated information</li>
                    <li><strong>Erasure</strong> — request deletion of your data where no longer necessary</li>
                    <li><strong>Object</strong> — object to the processing of your data for certain purposes</li>
                    <li><strong>Complaint</strong> — lodge a complaint with the National Privacy Commission (NPC)</li>
                </ul>
            </div>

